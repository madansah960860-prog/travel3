  <div class="wrap">
    <div class="section-head" style="border-bottom-color:#FF4A1C;">
      <h2 id="does-h">Four things the planner does that a notes app does not</h2>
      <p class="mono-note" style="margin:0;max-width:34ch;">Every feature below is live today on the free tier unless the card says Pro.</p>
    </div>

    <div class="cols-2" style="gap:0;">
      <div class="step" style="border-right-width:2px;">
        <span class="step__n">01</span>
        <div class="step__body">
          <h3>Time-stamped day plans</h3>
          <p>Each stop carries an arrival time, a duration, and the travel time from the stop before it.
          When you overfill a day, the plan shows you the stop that pushes past sunset instead of letting
          you find out in the parking lot.</p>
        </div>
      </div>
      <div class="step">
        <span class="step__n">02</span>
        <div class="step__body">
          <h3>A running cost per person</h3>
          <p>Entry fees, parking, tours, meals, and lodging roll into a daily and trip total in USD.
          Change the traveler count and the whole plan re-prices. No surprise at the end of the month.</p>
        </div>
      </div>
      <div class="step">
        <span class="step__n">03</span>
        <div class="step__body">
          <h3>Checklists tied to the trip</h3>
          <p>Cold and wet, desert, carry-on only, international documents. Pick the profile and the
          checklist assembles itself, then remembers what you have already packed.</p>
        </div>
      </div>
      <div class="step" style="border-right-width:2px;">
        <span class="step__n">04</span>
        <div class="step__body">
          <h3>Offline PDF export <span class="label label--accent" style="vertical-align:middle;">Pro</span></h3>
          <p>One page per day, printable, readable with no signal in a canyon. Pro members export
          unlimited trips. Free members can buy a single export for $6.</p>
        </div>
      </div>
    </div>
  </div>
</section>

