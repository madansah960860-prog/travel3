          driving distance, and into what you can actually afford after the flight is paid for.
        </p>
        <p>
          Hardpack was built by three people who kept ruining their own vacations with optimistic
          spreadsheets. You add a stop, we ask the boring questions: what time does it open, how far
          is it from the last thing, what does it cost per person, and what happens if it rains.
          The day plan you end up with is one you can hand to somebody at the trailhead.
        </p>
        <p>
          It works for a two-week international trip and it works for a three-day drive out of
          Denver with eleven PTO days left in the year.
